import { readFileSync } from "node:fs";

const HEADER = "// Generated by scripts/gen-content.ts from docs/content. Do not edit by hand.\n";

export function parseTruth(md: string): string[] {
  const rows = md.split("\n").filter((l) => /^\|\s*\d+\s*\|/.test(l));
  return rows.map((l) => l.split("|")[2].trim());
}

export function parsePrompts(md: string): string[] {
  return md
    .split("\n")
    .filter((l) => /^\d+\.\s/.test(l))
    .map((l) => l.replace(/^\d+\.\s*/, "").trim());
}

export function generate(root = "."): { truth: string; prompts: string } {
  const truth = parseTruth(readFileSync(`${root}/docs/content/truth-or-truth.md`, "utf8"));
  const prompts = parsePrompts(readFileSync(`${root}/docs/content/composer-prompts.md`, "utf8"));
  if (truth.length !== 100) throw new Error(`Expected 100 questions, found ${truth.length}`);
  if (prompts.length !== 30) throw new Error(`Expected 30 prompts, found ${prompts.length}`);
  const list = (xs: string[]) => xs.map((x) => `  ${JSON.stringify(x)},`).join("\n");
  return {
    truth: `${HEADER}export const TRUTH_OR_TRUTH: readonly string[] = [\n${list(truth)}\n];\n`,
    prompts: `${HEADER}
export const COMPOSER_PROMPTS: readonly string[] = [
${list(prompts)}
];

/** others: every member but the writer. One of them, at random, is "the other one". */
export function promptFor(
  others: readonly string[],
  pick: number = Math.floor(Math.random() * COMPOSER_PROMPTS.length),
  who: number = Math.floor(Math.random() * Math.max(others.length, 1)),
): string {
  const prompt = COMPOSER_PROMPTS[pick % COMPOSER_PROMPTS.length];
  return others.length === 0 ? prompt : prompt.replace("the other one", others[who % others.length]);
}
`,
  };
}
